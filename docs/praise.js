const RECENT_KEY = "slot036.recentPraise";
export function pickPraise(kind, vars = {}, sub) {
  let pool = PRAISE[kind]; if (sub != null) pool = pool[sub];
  if (!pool || !pool.length) return "";
  const recent = JSON.parse(localStorage.getItem(RECENT_KEY) || "[]");
  const fresh = pool.filter((l) => !recent.includes(l));
  const line = (fresh.length ? fresh : pool)[Math.floor(Math.random() * (fresh.length || pool.length))];
  recent.unshift(line); localStorage.setItem(RECENT_KEY, JSON.stringify(recent.slice(0, 40)));
  return fill(line, vars);
}
export function fill(line, { you = "", ex = "", n = "" } = {}) {
  let s = line.replace(/\{ex\}/g, ex).replace(/\{n\}/g, n);
  s = you ? s.replace(/\{you\}/g, you) : s.replace(/\{you\}、?の?/g, "").replace(/今日の、/g, "今日の");
  return s.replace(/^、/, "").trim();
}
